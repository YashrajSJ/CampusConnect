// Endpoint: GET or POST /api/dev/seed-projects
router.all("/seed-projects", async (_req, res) => {
  try {
    // 1. Seed students
    const userMap = {};
    for (const userData of SEED_USERS) {
      const user = await User.findOneAndUpdate(
        { clerkId: userData.clerkId },
        { $set: userData },
        { upsert: true, new: true }
      );
      const key = userData.clerkId.split("_")[2];
      userMap[key] = user;
    }

    // 2. Clear old seeded projects only (preserves user personal projects)
    const seedUserIds = Object.values(userMap).map((u) => u._id);
    await Project.deleteMany({ creatorId: { $in: seedUserIds } });

    // 3. Create 15 projects
    const created = [];
    for (const p of SEED_PROJECTS_DEF) {
      const creator = userMap[p.creatorKey] || Object.values(userMap)[0];
      const deadline = futureDate(p.daysUntilDeadline);

      const doc = await Project.create({
        title: p.title,
        description: p.description,
        category: p.category,
        targetRole: p.targetRole,
        stage: p.stage,
        commitment: p.commitment,
        mode: p.mode,
        requiredSkills: p.requiredSkills,
        teamSize: p.teamSize,
        existingMembersCount: p.existingMembersCount,
        whatsappNumber: p.whatsappNumber,
        creatorId: creator._id,
        members: [creator._id],
        isOpen: true,
        deadline,
      });
      created.push(doc.title);
    }

    res.json({
      ok: true,
      message: `Successfully seeded ${created.length} campus projects!`,
      creatorsCount: Object.keys(userMap).length,
      projects: created,
    });
  } catch (err) {
    console.error("Seed API error:", err);
    res.status(500).json({ ok: false, error: err.message });
  }
});

export default router;
